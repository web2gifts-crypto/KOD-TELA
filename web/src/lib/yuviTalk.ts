// реплику по данным пользователя (настроение, цикл, серия отметок).
//
// Без повторов: приложение помнит, когда каждая реплика показывалась (store.talkSeen).
//  • лёгкие реплики идут от давно не показанных к недавним — пока весь набор
//    не прочитан, одна и та же не повторится, даже между запусками;
//  • реплика по данным показывается не чаще раза в день.
//
// Правила текстов: без диагнозов, без «норма/не норма», без лекарств и добавок,
// без давления («ты должна»). Факты — общеизвестные; финальные тексты согласовать с медэкспертом.

