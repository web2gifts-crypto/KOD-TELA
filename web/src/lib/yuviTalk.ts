export interface TalkContext {
  today: ISODate
  info: DayInfo | null
  mood: number | undefined
  streak: number
  periodInDays: number | null
  fertile: boolean
  badLabs: LabEval[]
  hasLabs: boolean
}

/** Комментарии к данным пользователя */
function contextLines(c: TalkContext): string[] {
  const out: string[] = []
  out.push(c.mood ? MOOD_REACTIONS[c.mood] : 'Как настроение? Отметь его — я поменяю цвет 🎨')
  if (c.info) out.push(PHASE_LINES[c.info.phase] ?? `Сейчас ${PHASES[c.info.phase].name.toLowerCase()}.`)
  if (c.periodInDays !== null && c.periodInDays > 0 && c.periodInDays <= 3)
    out.push(`Месячные примерно через ${c.periodInDays} дн. — положи нужное в сумку 👜`)
  if (c.fertile) out.push('Сейчас фертильные дни — я отметил их в календаре 📅')
  if (c.streak >= 2) out.push(`Уже ${c.streak} ${plural(c.streak, 'день', 'дня', 'дней')} подряд отмечаешь настроение — ты супер! 🔥`)
  if (c.badLabs.length) out.push(`Загляни в «Юви советует» — там про ${c.badLabs[0].def.name.toLowerCase()} 👀`)
  else if (!c.hasLabs) out.push('Загрузишь анализы — расскажу, что они значат, простыми словами 🔬')
  out.push('Я собрал советы на сегодня — загляни, когда будет минутка 👀')
  return out
}

function seeded(seed: string) {
  let h = 2166136261
  for (let i = 0; i < seed.length; i++) h = Math.imul(h ^ seed.charCodeAt(i), 16777619)
  return () => {
    h = Math.imul(h ^ (h >>> 15), 2246822507)
    h = Math.imul(h ^ (h >>> 13), 3266489909)
    return ((h ^= h >>> 16) >>> 0) / 4294967296
  }
}

function shuffle<T>(xs: T[], rnd: () => number): T[] {
  const a = [...xs]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

/** Лента реплик на день: 2 «лёгкие» (факт/пожелание/шутка) на 1 комментарий к данным */
export function yuviTalk(c: TalkContext): string[] {
  const rnd = seeded(c.today)
  const fun = shuffle([...FACTS, ...WISHES, ...JOKES], rnd)
  const ctx = shuffle(contextLines(c), rnd)
  const out: string[] = []
  let f = 0
  let k = 0
  while (f < fun.length) {
    out.push(fun[f++])
    if (f < fun.length) out.push(fun[f++])
    if (ctx.length) out.push(ctx[k++ % ctx.length])
  }
  return out
}
