export interface TalkContext {
  today: ISODate
  info: DayInfo | null
  mood: number | undefined
  streak: number
  periodInDays: number | null
  fertile: boolean
  hasLabs: boolean
}

/** Реплики по данным пользователя */
export function contextLines(c: TalkContext): TalkLine[] {
  const out: TalkLine[] = []
  const add = (id: string, text: string) => out.push({ id: `c:${id}`, text, kind: 'ctx' })
  if (c.mood) add(`mood${c.mood}`, MOOD_REACTIONS[c.mood])
  else add('ask-mood', 'Как ты сегодня? Отметь настроение — я поменяю цвет 🎨')
  if (c.info) add(`phase-${c.info.phase}`, PHASE_LINES[c.info.phase] ?? `Сейчас ${PHASES[c.info.phase].name.toLowerCase()}.`)
  if (c.periodInDays !== null && c.periodInDays > 0 && c.periodInDays <= 3)
    add('period-soon', `По прогнозу месячные примерно через ${c.periodInDays} ${plural(c.periodInDays, 'день', 'дня', 'дней')} — может, положить нужное в сумку? 👜`)
  if (c.fertile) add('fertile', 'По прогнозу сейчас фертильные дни — они отмечены в календаре 📅')
  if (c.streak >= 2) add('streak', `Уже ${c.streak} ${plural(c.streak, 'день', 'дня', 'дней')} подряд отмечаешь настроение — ты супер! 🔥`)
  if (!c.hasLabs) add('labs', 'Можно вести дневник анализов — будет видно, как меняются показатели 📈')
  add('recs', 'Я собрал идеи на сегодня — загляни, когда будет минутка 👀')
  return out
}

function seeded(seed: string) {
  let h = 2166136261
  for (let i = 0; i < seed.length; i++) h = Math.imul(h ^ seed.charCodeAt(i), 16777619)
  return () => {
    h = Math.imul(h ^ (h >>> 15), 2246822507)
    h = Math.imul(h ^ (h >>> 13), 3266489909)
    return ((h ^= h >>> 16) >>> 0) / 4294967296
  }
}

function shuffle<T>(xs: T[], rnd: () => number): T[] {
  const a = [...xs]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

/** id реплики → дата последнего показа */
export type TalkSeen = Record<string, ISODate>

/**
 * Лента реплик: 2 лёгкие на 1 по данным.
 * Лёгкие — сначала никогда не показанные, затем давно показанные (не повторяются, пока не кончится набор).
 * По данным — только те, что сегодня ещё не показывались.
 */
export function yuviTalk(c: TalkContext, seen: TalkSeen = {}): TalkLine[] {
  const rnd = seeded(c.today)
  // перемешиваем, затем стабильно сортируем по давности показа: перемешивание решает ничьи
  const funs = shuffle(FUN_LINES, rnd).sort((a, b) => (seen[a.id] ?? '').localeCompare(seen[b.id] ?? ''))
  const ctx = shuffle(contextLines(c), rnd).filter((l) => seen[l.id] !== c.today)
  const out: TalkLine[] = []
  let k = 0
  for (let f = 0; f < funs.length; ) {
    out.push(funs[f++])
    if (f < funs.length) out.push(funs[f++])
    if (k < ctx.length) out.push(ctx[k++])
  }
  return out
}

/** Пометить реплику показанной сегодня */
export function markSeen(seen: TalkSeen, id: string, today: ISODate): TalkSeen {
  return { ...seen, [id]: today }
}
