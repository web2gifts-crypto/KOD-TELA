export const ARTICLE_BY_ID = Object.fromEntries(ARTICLES.map((a) => [a.id, a]))

/** Статьи для текущей фазы — сначала по фазе, потом общие */
export function articlesFor(phase: Phase | null, mode: 'cycle' | 'conceive' | 'pregnancy' = 'cycle'): Article[] {
  const pool = ARTICLES.filter((a) => mode === 'conceive' || a.topic !== 'conceive')
  return [...pool.filter((a) => phase && a.phase === phase), ...pool.filter((a) => a.phase === null), ...pool.filter((a) => a.phase && a.phase !== phase)]
}
