export function buildVerdict(symptom: string, answers: Answers, phase: Phase | null): Verdict {
  const topic = TOPICS.find((t) => t.match.test(symptom))
  const phaseNote = phase ? ` Сейчас у тебя ${PHASES[phase].name.toLowerCase()} — это тоже влияет на самочувствие.` : ''

  const redFlag = answers.extra === 'Температура выше 38°' || answers.extra === 'Кровь вне месячных'
  const long = answers.duration === 'Больше 2 недель'
  const strong = answers.severity === 'Очень сильно'

  if (redFlag || (strong && long)) {
    return {
      level: 'doctor',
      title: 'Стоит показаться врачу в ближайшие дни',
      explanation:
        (redFlag ? `«${answers.extra}» — повод для очного осмотра.` : 'Сильный симптом дольше двух недель нужно проверить.') +
        phaseNote,
      plan: [
        answers.extra === 'Кровь вне месячных' ? 'Запишись к гинекологу' : 'Запишись к терапевту',
        ...(topic?.plan.slice(0, 2) ?? ['Запиши, когда и как проявляется симптом']),
        'Если станет резко хуже — вызывай скорую',
      ],
    }
  }

  if (strong || long) {
    return {
      level: 'doctor',
      title: 'Ничего срочного, но лучше проверить',
      explanation: (topic?.why ?? 'Симптом держится или сильно мешает — лучше разобраться с причиной.') + phaseNote,
      plan: [...(topic?.plan ?? ['Отмечай симптом в дневнике']), 'Если за 2 недели не станет лучше — к терапевту'],
    }
  }

  return {
    level: 'norm',
    title: 'Похоже на вариант нормы',
    explanation: (topic?.why ?? 'Такие ощущения часто бывают временными и связаны с режимом, стрессом или фазой цикла.') + phaseNote,
    plan: topic?.plan ?? ['Высыпайся 7–9 часов', 'Пей достаточно воды', 'Отмечай самочувствие в дневнике цикла'],
  }
}

