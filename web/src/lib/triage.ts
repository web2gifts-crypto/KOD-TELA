/** Красные флаги — сразу к скорой. Полный список дают медицинские эксперты. */
const EMERGENCY = [
  /сильн[а-яё]* кровотеч/i,
  /кровотечени[а-яё]* (не останавл|сильн|обильн)/i,
  /остр[а-яё]* боль/i,
  /боль в груди/i,
  /теряю сознани|потеряла сознани|обморок/i,
  /не могу дышать|задыха/i,
  /суицид|покончить с собой|не хочу жить|убить себя/i,
  /беременн[а-яё]*.*(боль|кровь|кровотеч)/i,
]

export function isEmergency(text: string): boolean {
  return EMERGENCY.some((r) => r.test(text))
}

export function emergencyVerdict(text: string): Verdict {
  const mental = /суицид|покончить|не хочу жить|убить себя/i.test(text)
  return mental
    ? {
        level: 'emergency',
        title: 'Тебе сейчас очень тяжело — и это важно',
        explanation:
          'Ты не одна. Пожалуйста, прямо сейчас поговори с живым человеком: специалисты помогают бесплатно и анонимно.',
        plan: ['Позвони на телефон доверия 8-800-2000-122 (бесплатно, круглосуточно)', 'Если есть угроза жизни — звони 112', 'Побудь рядом с близким человеком'],
      }
    : {
        level: 'emergency',
        title: 'Срочно вызови скорую — 103 или 112',
        explanation: 'Описанные симптомы могут быть признаком состояния, которое требует немедленной помощи врача.',
        plan: ['Позвони 103 (или 112 с мобильного)', 'Не принимай обезболивающие до осмотра врача', 'Не оставайся одна — позови кого-то рядом'],
      }
}

