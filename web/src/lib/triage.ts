export function topicFor(symptom: string): Topic {
  return TOPICS.find((t) => t.match.test(symptom)) ?? GENERAL
}

/** Общие поводы обратиться к врачу — показываются в каждом ответе */
const ALWAYS_DOCTOR = ['Если симптом держится дольше двух недель или возвращается', 'Если становится сильнее или мешает обычной жизни', 'Если появились температура, кровь вне месячных, сильная боль'] as const

export function buildVerdict(symptom: string, answers: Answers, phase: Phase | null): Verdict {
  const topic = topicFor(symptom)
  const phaseNote = phase ? ` Сейчас у тебя ${PHASES[phase].name.toLowerCase()} — отметь это, когда будешь рассказывать врачу.` : ''

  const redFlag = answers.extra === 'Температура выше 38°' || answers.extra === 'Кровь вне месячных'
  const long = answers.duration === 'Больше 2 недель'
  const strong = answers.severity === 'Очень сильно'
  const hormones = answers.meds === 'Гормональные / ОК' || answers.meds === 'Другие лекарства'

  const whenDoctor = [`Обратиться можно к ${topic.specialist}`, ...ALWAYS_DOCTOR]
  if (hormones) whenDoctor.splice(1, 0, 'Расскажи врачу о лекарствах, которые принимаешь')

  if (redFlag || strong || long) {
    const reason = redFlag
      ? `«${answers.extra}» — повод показаться врачу очно.`
      : strong && long
        ? 'Симптом сильный и держится больше двух недель — его стоит обсудить с врачом.'
        : strong
          ? 'Симптом сильно мешает — лучше не терпеть и обсудить его с врачом.'
          : 'Симптом держится больше двух недель — стоит рассказать о нём врачу.'
    return {
      level: 'doctor',
      title: 'Лучше обратиться к врачу в ближайшие дни',
      explanation: `${reason} ${topic.about}${phaseNote}`,
      plan: [`Запишись к ${topic.specialist}`, ...topic.selfcare.slice(-1), 'Если станет резко хуже — звони 103 или 112'],
      whenDoctor: [],
    }
  }

  return {
    level: 'info',
    title: 'Вот что можно знать',
    explanation: topic.about + phaseNote,
    plan: topic.selfcare,
    whenDoctor,
  }
}

