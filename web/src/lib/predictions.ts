function hash(s: string): number {
  let h = 2166136261
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return h >>> 0
}

export function predictionFor(date: ISODate, userId: number): string {
  return PREDICTIONS[hash(`${date}:${userId}`) % PREDICTIONS.length]
}
