"""Медицинская безопасность ответов — дублирует web/src/lib/triage.ts.

1) Красные флаги во входящем сообщении → экстренный ответ (103/112), модель не вызывается.
2) Ответ модели с «нормой», диагнозом или дозировкой не отдаётся — клиент покажет ответ по правилам.
Списки согласуются с медицинским экспертом; при изменении — правьте и здесь, и в triage.ts.
"""

import re

_I = re.IGNORECASE

EMERGENCY = [
    re.compile(p, _I)
    for p in [
        r"сильн[а-яё]* кровотеч",
        r"кровотечени[а-яё]* (не останавл|сильн|обильн)",
        r"остр[а-яё]* боль",
        r"боль в груди",
        r"теряю сознани|потеряла сознани|обморок",
        r"не могу дышать|задыха",
        r"суицид|покончить с собой|не хочу жить|убить себя",
        r"беременн[а-яё]*.*(бол[ьиея]|кров)|(бол[ьиея]|кров)[а-яё]*.*беременн",
    ]
]

MENTAL = re.compile(r"суицид|покончить|не хочу жить|убить себя", _I)

FORBIDDEN = [
    re.compile(p, _I)
    for p in [
        r"вариант нормы",
        r"(^|[^а-яё])(это|в пределах|в) норм[аеы](?![а-яё])",
        r"ничего страшного",
        r"у тебя [а-яё]*(дефицит|анемия|гипотиреоз|спкя)",
        r"\d\s?(мг|мкг|ме)(?![а-яё])",
        r"(прими|принимай|выпей) [а-яё]*(таблет|ибупрофен|парацетамол|но-шп|магни|желез)",
    ]
]


def is_emergency(text: str) -> bool:
    return any(r.search(text) for r in EMERGENCY)


def violates_policy(text: str) -> bool:
    return any(r.search(text) for r in FORBIDDEN)


def emergency_reply(text: str) -> dict:
    if MENTAL.search(text):
        verdict = {
            "level": "emergency",
            "title": "Тебе сейчас очень тяжело — и это важно",
            "explanation": "Ты не одна. Пожалуйста, прямо сейчас поговори с живым человеком: специалисты помогают бесплатно и анонимно.",
            "plan": ["Позвони на телефон доверия 8-800-2000-122 (бесплатно, круглосуточно)", "Если есть угроза жизни — звони 112", "Побудь рядом с близким человеком"],
            "whenDoctor": [],
        }
    else:
        verdict = {
            "level": "emergency",
            "title": "Срочно вызови скорую — 103 или 112",
            "explanation": "То, что ты описываешь, может требовать срочной помощи. Не жди — лучше перестраховаться.",
            "plan": ["Позвони 103 (или 112 с мобильного)", "Опиши диспетчеру, что чувствуешь и когда началось", "Не оставайся одна — позови кого-то рядом"],
            "whenDoctor": [],
        }
    return {"text": "Это важно — не откладывай.", "verdict": verdict}


